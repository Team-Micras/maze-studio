const HEADER = `/**
 * The Phosphor icons the app uses, in the regular weight only (DESIGN.md 4). Generated by
 * \`bun run icons\` (\`scripts/icons.ts\`) from \`@phosphor-icons/core\`; not to be edited by hand.
 *
 * @module
 */

import type { JSX, SVGProps } from 'react';

/**
 * The props of an icon: its side, 1em by default, and any attribute of an SVG; hidden from screen
 * readers unless \`aria-hidden\` says otherwise, since what it means is named beside it.
 */
export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'children'> {
  readonly size?: number | string;
}

/** An icon. */
export type Icon = (props: IconProps) => JSX.Element;

function Glyph({
  d,
  size = '1em',
  'aria-hidden': hidden = true,
  ...props
}: IconProps & { readonly d: string }) {
  return (
    <svg
      aria-hidden={hidden}
      fill="currentColor"
      height={size}
      viewBox="0 0 256 256"
      width={size}
      xmlns="http://www.w3.org/2000/svg"
      {...props}
    >
      <path d={d} />
    </svg>
  );
}
`;

function fileName(name: string): string {
  return name.replaceAll(/(?<=[a-z0-9])([A-Z])/g, '-$1').toLowerCase();
}

/** The path of an icon's regular SVG, which must be one `path` on a 256 grid. */
function pathOf(name: string): string {
  const svg = readFileSync(join(REGULAR, `${fileName(name)}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"\/>/g)].map((match) => match[1] ?? '');
  const elements = svg.match(/<(?!\/)[a-z]+/g) ?? [];

  if (!svg.includes('viewBox="0 0 256 256"') || paths.length !== 1 || elements.length !== 2) {
    throw new Error(`${name} is not one path on a 256 grid`);
  }

  return paths[0] ?? '';
}

/** The text of `src/ui/icons.tsx`. */
export function iconsModule(): string {
  const icons = ICONS.map((name) => {
    const d = pathOf(name);
    const line = `  return <Glyph d="${d}" {...props} />;`;
    const body =
      line.length <= LINE_WIDTH
        ? line
        : `  return (\n    <Glyph\n      d="${d}"\n      {...props}\n    />\n  );`;
    return `\n/** Phosphor's \`${fileName(name)}\`. */\nexport function ${name}(props: IconProps) {\n${body}\n}\n`;
  });
  return `${HEADER}${icons.join('')}`;
}

if (import.meta.main) {
  writeFileSync(ICONS_MODULE, iconsModule());
}
